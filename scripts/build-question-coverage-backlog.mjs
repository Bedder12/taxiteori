import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function files(directory, suffix) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path, suffix) : entry.name.endsWith(suffix) ? [path] : [];
  });
}

const requirements = JSON.parse(readFileSync('data/curriculum/requirements.json', 'utf8')).requirements.filter((requirement) => requirement.active);
const questions = files('data/questions', '-questions.json').flatMap((path) => JSON.parse(readFileSync(path, 'utf8')).questions);
const weak = requirements.map((requirement) => ({
  requirement,
  count: questions.filter((question) => question.requirement_keys?.includes(requirement.stable_key)).length,
})).filter((entry) => entry.count < 3);

function recommendation(requirement) {
  if (requirement.requires_calculation) return 'calculation';
  if (requirement.requires_image || requirement.requires_map) return 'visual';
  if (['APPLY', 'ASSESS', 'USE'].includes(requirement.competency_type)) return 'scenario/application';
  return 'recall/application';
}

function priority(count) {
  return count <= 1 ? 'P1-high' : count === 2 ? 'P1-medium' : 'P2';
}

const lines = [
  '# Question Coverage Backlog',
  '',
  'Generated from active curriculum requirements. No questions are generated by this backlog task.',
  '',
  `Weak requirements: ${weak.length}`,
  '',
  '| Priority | Requirement | Subject | Existing questions | Competency | Recommended minimum | Recommended question form |',
  '| --- | --- | --- | ---: | --- | ---: | --- |',
];
for (const { requirement, count } of weak) {
  lines.push(`| ${priority(count)} | ${requirement.stable_key} | ${requirement.subject} | ${count} | ${requirement.competency_type} | 3 | ${recommendation(requirement)} |`);
}

lines.push('', '## Prioritization', '', '- P1-high: one or fewer existing questions; highest risk of weak assessment coverage.', '- P1-medium: two existing questions; add a second competency angle before public beta.', '- P2: reserved for later balancing after P1 coverage is addressed.', '', 'Visual recommendations only apply where the curriculum requirement explicitly requires an image/map. Existing visual metadata remains subject to the visual-required asset gate.');
writeFileSync('docs/question-coverage-backlog.md', `${lines.join('\n')}\n`);
console.log(`Wrote ${weak.length} weak requirement backlog entries.`);